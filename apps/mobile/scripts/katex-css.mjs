// Writes src/dom/katex.generated.css: KaTeX's stylesheet with its fonts inlined
// as woff2 data URIs. Metro can't bundle CSS that points at font files, and
// inlining keeps lessons typeset offline. Run after upgrading katex: `pnpm katex-css`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const dist = dirname(require.resolve("katex/dist/katex.min.css"));
const css = readFileSync(join(dist, "katex.min.css"), "utf8").replace(/src:([^;}]+)/g, (_, sources) => {
  const woff2 = /url\((fonts\/[^)]+\.woff2)\)/.exec(sources)?.[1];
  if (!woff2) throw new Error(`No woff2 source in: ${sources}`);
  return `src:url(data:font/woff2;base64,${readFileSync(join(dist, woff2)).toString("base64")}) format("woff2")`;
});
const out = new URL("../src/dom/katex.generated.css", import.meta.url);
writeFileSync(out, `/* Generated by scripts/katex-css.mjs from katex ${require("katex/package.json").version}. Do not edit. */\n${css}\n`);
console.log(`Wrote ${out.pathname} (${Math.round(css.length / 1024)} KB)`);
